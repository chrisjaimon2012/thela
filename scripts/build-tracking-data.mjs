#!/usr/bin/env node
/**
 * Compile the vendored tracking-number dataset into a Worker-sized module.
 *
 * The raw data is 164 KB of JSON across twelve files, most of it service-type
 * lookups, prose descriptions and test fixtures. The Worker needs four things
 * per pattern — how to recognise a number, how to check its check digit, where
 * to send a customer, and (for S10) which national postal operator a country
 * code belongs to. Everything else stays in `vendor/` where the tests read it.
 *
 * Generating rather than importing also means the regexes are validated at
 * build time. A pattern that does not compile fails `npm run build:tracking`
 * rather than throwing inside a request on somebody's shop.
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const SRC = 'vendor/tracking-number-data/couriers';
const OUT = 'src/lib/shipping/tracking-data.generated.ts';

/** Upstream writes a regex as either a string or an array of fragments to join. */
const joinPattern = (r) => (Array.isArray(r) ? r.join('') : r);

const patterns = [];
let s10Couriers = null;

for (const file of readdirSync(SRC).filter((f) => f.endsWith('.json')).sort()) {
  const doc = JSON.parse(readFileSync(join(SRC, file), 'utf8'));

  for (const entry of doc.tracking_numbers) {
    const source = joinPattern(entry.regex);

    // Fail the build, not a request, on a pattern this runtime cannot compile.
    try {
      new RegExp(source);
    } catch (err) {
      console.error(`\n${file}: pattern for "${entry.name}" does not compile\n  ${err.message}\n`);
      process.exit(1);
    }

    const checksum = entry.validation?.checksum ?? null;

    patterns.push({
      id: entry.id ?? `${doc.courier_code}-${entry.name}`,
      courier: doc.name,
      courierCode: doc.courier_code,
      name: entry.name,
      source,
      url: entry.tracking_url ?? null,
      checksum: checksum && {
        name: checksum.name,
        evens: checksum.evens_multiplier ?? null,
        odds: checksum.odds_multiplier ?? null,
        // Weight from the right rather than the left. Two entries use it, and
        // dropping it silently marks their real numbers invalid.
        reverse: checksum.reverse === true,
        weightings: checksum.weightings ?? null,
        modulo1: checksum.modulo1 ?? null,
        modulo2: checksum.modulo2 ?? null,
      },
      // Some carriers checksum a number that is longer than the one printed on
      // the label: USPS 91, FedEx SmartPost and OnTrac all re-attach an implied
      // prefix first. Without this their genuine numbers fail validation.
      prependIf: entry.validation?.serial_number_format?.prepend_if
        ? {
            unless: entry.validation.serial_number_format.prepend_if.matches_regex,
            content: entry.validation.serial_number_format.prepend_if.content,
          }
        : null,
    });

    // S10 is the Universal Postal Union standard: its country code identifies
    // the national operator, which is how one pattern covers 191 countries.
    const courierLookup = (entry.additional ?? []).find((a) => a.name === 'Courier');
    if (courierLookup) {
      s10Couriers = Object.fromEntries(
        courierLookup.lookup
          .filter((l) => l.matches && l.courier)
          .map((l) => [l.matches, l.courier]),
      );
    }
  }
}

if (!s10Couriers) {
  console.error('No S10 country->courier lookup found. That is the global tail; refusing to build without it.');
  process.exit(1);
}

const banner = `// GENERATED by scripts/build-tracking-data.mjs — do not edit.
//
// Source: vendor/tracking-number-data (MIT, jkeen/tracking_number_data).
// See vendor/tracking-number-data/PINNED.md for the pinned commit and why
// this is vendored rather than depended on.
//
// Run \`npm run build:tracking\` after updating the vendored data.
`;

const body = `${banner}
export interface Checksum {
  name: string;
  evens: number | null;
  odds: number | null;
  reverse: boolean;
  weightings: number[] | null;
  modulo1: number | null;
  modulo2: number | null;
}

/** An implied prefix re-attached to the serial before the check digit is computed. */
export interface PrependIf {
  /** Apply the prefix only when the serial does NOT already match this. */
  unless: string;
  content: string;
}

export interface TrackingPattern {
  id: string;
  /** The carrier this number belongs to, as a human reads it. */
  courier: string;
  courierCode: string;
  name: string;
  /** Regex source. Tolerates whitespace between characters, as printed labels do. */
  source: string;
  /** \`%s\` is replaced with the number. Null where the carrier publishes none. */
  url: string | null;
  checksum: Checksum | null;
  prependIf: PrependIf | null;
}

export const PATTERNS: readonly TrackingPattern[] = ${JSON.stringify(patterns, null, 2)};

/**
 * ISO 3166-1 alpha-2 to national postal operator, from the UPU S10 standard.
 * One entry per member country, which is why a single pattern resolves
 * "EE123456789IN" to India Post and "CP123456789FR" to La Poste.
 */
export const S10_COURIERS: Readonly<Record<string, string>> = ${JSON.stringify(s10Couriers, null, 2)};
`;

writeFileSync(OUT, body);

const kb = (Buffer.byteLength(body) / 1024).toFixed(1);
console.log(`${OUT}: ${patterns.length} patterns, ${Object.keys(s10Couriers).length} S10 countries, ${kb} KB`);
